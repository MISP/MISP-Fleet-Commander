<template>
    <b-modal
        id="modal-organisation-form"
        size="lg"
        scrollable
        :title="isEdit ? `Edit ${org.name}` : `Add an organisation to ${server.name}`"
        @show="reset"
    >
        <b-form class="org-form" novalidate @submit.prevent="save">
            <b-alert :show="error !== null" variant="danger" class="form-alert">{{ error }}</b-alert>

            <b-form-group
                label="Name"
                label-for="org-form-name"
                :state="nameState"
                :invalid-feedback="nameFeedback"
            >
                <b-form-input id="org-form-name" v-model="form.name" :state="nameState" autocomplete="off" maxlength="255" required></b-form-input>
            </b-form-group>

            <div class="field-row field-row-kind">
            <b-form-group label="Kind" :description="form.local ? 'Has users on this server.' : 'Known from sync, sharing groups or events.'">
                <div class="kind-choice" role="radiogroup" aria-label="Kind">
                    <button type="button" role="radio" :aria-checked="form.local ? 'true' : 'false'" :class="['kind-option', { active: form.local }]" @click="form.local = true">
                        <i class="fas fa-home" aria-hidden="true"></i> Local
                    </button>
                    <button type="button" role="radio" :aria-checked="!form.local ? 'true' : 'false'" :class="['kind-option', { active: !form.local }]" @click="form.local = false">
                        <i class="fas fa-globe" aria-hidden="true"></i> External
                    </button>
                </div>
            </b-form-group>

            <b-form-group
                label="UUID"
                label-for="org-form-uuid"
                :state="uuidState"
                invalid-feedback="Not a UUID (such as 5f6e7d8c-1a2b-4c3d-8e9f-0a1b2c3d4e5f)"
                :description="isEdit ? '' : 'Leave empty for a new UUID. Use the UUID it has on other servers to make it the same organisation.'"
            >
                <b-form-input
                    id="org-form-uuid"
                    v-model="form.uuid"
                    :state="uuidState"
                    class="uuid-input"
                    autocomplete="off"
                    spellcheck="false"
                    :placeholder="isEdit ? '' : 'Generated by MISP'"
                ></b-form-input>
            </b-form-group>
            </div>

            <b-alert :show="uuidChanged" variant="warning" class="form-alert">
                <i class="fas fa-exclamation-triangle mr-1" aria-hidden="true"></i>
                Other servers know this organisation by its UUID: what they sync will still name the old one. Change it only to match the UUID the rest of the fleet uses.
            </b-alert>
            <b-alert :show="syncWarning" variant="warning" class="form-alert">
                <i class="fas fa-sync-alt mr-1" aria-hidden="true"></i>
                Sync relies on this organisation: {{ syncReasons.map(reason => reason.text).join("; ") }}.
            </b-alert>

            <div class="field-row">
                <b-form-group label="Type" label-for="org-form-type" class="field-third">
                    <b-form-input id="org-form-type" v-model="form.type" list="org-form-types" autocomplete="off" maxlength="255" placeholder="CSIRT, ADMIN…"></b-form-input>
                    <datalist id="org-form-types"><option v-for="value in suggestions.type" :key="value" :value="value"></option></datalist>
                </b-form-group>
                <b-form-group label="Sector" label-for="org-form-sector" class="field-third">
                    <b-form-input id="org-form-sector" v-model="form.sector" list="org-form-sectors" autocomplete="off" maxlength="255"></b-form-input>
                    <datalist id="org-form-sectors"><option v-for="value in suggestions.sector" :key="value" :value="value"></option></datalist>
                </b-form-group>
                <b-form-group label="Nationality" label-for="org-form-nationality" class="field-third">
                    <b-form-input id="org-form-nationality" v-model="form.nationality" list="org-form-nationalities" autocomplete="off" maxlength="255"></b-form-input>
                    <datalist id="org-form-nationalities"><option v-for="value in suggestions.nationality" :key="value" :value="value"></option></datalist>
                </b-form-group>
            </div>

            <b-form-group label="Description" label-for="org-form-description">
                <b-form-textarea id="org-form-description" v-model="form.description" rows="2" max-rows="6"></b-form-textarea>
            </b-form-group>
            <b-form-group label="Contacts" label-for="org-form-contacts">
                <b-form-textarea id="org-form-contacts" v-model="form.contacts" rows="2" max-rows="6"></b-form-textarea>
            </b-form-group>
            <b-form-group
                label="Restricted to domains"
                label-for="org-form-domains"
                description="One per line. The users of this organisation must have an email address in one of them."
            >
                <b-form-textarea id="org-form-domains" v-model="form.restricted_to_domain" rows="2" max-rows="6" class="domains-input" spellcheck="false" placeholder="example.org"></b-form-textarea>
            </b-form-group>
            <button type="submit" class="d-none" aria-hidden="true" tabindex="-1"></button>
        </b-form>

        <template #modal-footer="{ cancel }">
            <span v-if="isEdit" class="footer-note">{{ changeCount === 0 ? "No change yet" : `${changeCount} change${changeCount === 1 ? "" : "s"}` }}</span>
            <b-button variant="secondary" @click="cancel()">Cancel</b-button>
            <b-button variant="primary" :disabled="saving || !canSave" @click="save">
                <b-spinner v-if="saving" small class="mr-1"></b-spinner>{{ isEdit ? "Save changes" : "Add organisation" }}
            </b-button>
        </template>
    </b-modal>
</template>

<script>
import api from "@/api/organisations"
import { changedFields, domainLines, normalisedName, UUID_PATTERN } from "@/helpers/organisations"

function emptyForm() {
    return {
        name: "",
        local: true,
        uuid: "",
        type: "",
        sector: "",
        nationality: "",
        description: "",
        contacts: "",
        restricted_to_domain: "",
    }
}

export default {
    name: "OrganisationFormModal",
    props: {
        server: {
            type: Object,
            required: true,
        },
        // The organisation to edit; null to add one
        org: {
            type: Object,
            default: null,
        },
        // The server's organisations: suggestions, and names already taken
        organisations: {
            type: Array,
            default: () => [],
        },
        syncReasons: {
            type: Array,
            default: () => [],
        },
    },
    data() {
        return {
            form: emptyForm(),
            saving: false,
            error: null,
            errorField: null,
        }
    },
    computed: {
        isEdit() {
            return this.org !== null
        },
        takenBy() {
            const name = normalisedName(this.form.name)
            if (name === "") {
                return null
            }
            return this.organisations.find(other => normalisedName(other.name) === name && (!this.org || other.uuid !== this.org.uuid)) || null
        },
        nameState() {
            if (this.errorField === "name") {
                return false
            }
            if (this.takenBy) {
                return false
            }
            return null
        },
        nameFeedback() {
            if (this.takenBy) {
                return `“${this.takenBy.name}” already exists on this server`
            }
            return this.errorField === "name" ? this.error : ""
        },
        uuidState() {
            const uuid = this.form.uuid.trim()
            if (this.errorField === "uuid") {
                return false
            }
            if (uuid === "") {
                return this.isEdit ? false : null
            }
            return UUID_PATTERN.test(uuid) ? null : false
        },
        uuidChanged() {
            return this.isEdit && this.form.uuid.trim().toLowerCase() !== this.org.uuid
        },
        syncWarning() {
            return this.isEdit && this.syncReasons.length > 0 &&
                (this.uuidChanged || this.form.name.trim() !== this.org.name)
        },
        changes() {
            return this.isEdit ? changedFields(this.org, this.form) : null
        },
        changeCount() {
            return this.changes ? Object.keys(this.changes).length : 0
        },
        canSave() {
            if (this.form.name.trim() === "" || this.takenBy || this.uuidState === false) {
                return false
            }
            return !this.isEdit || this.changeCount > 0
        },
        suggestions() {
            const collect = (field) => [...new Set(this.organisations.map(org => org[field]).filter(Boolean))].sort((a, b) => a.localeCompare(b))
            return { type: collect("type"), sector: collect("sector"), nationality: collect("nationality") }
        },
    },
    watch: {
        form: {
            handler() {
                if (this.errorField !== null) {
                    this.errorField = null
                }
            },
            deep: true,
        },
    },
    methods: {
        reset() {
            this.error = null
            this.errorField = null
            this.saving = false
            if (this.org) {
                this.form = {
                    name: this.org.name,
                    local: this.org.local,
                    uuid: this.org.uuid,
                    type: this.org.type,
                    sector: this.org.sector,
                    nationality: this.org.nationality,
                    description: this.org.description,
                    contacts: this.org.contacts,
                    restricted_to_domain: (this.org.restricted_to_domain || []).join("\n"),
                }
            } else {
                this.form = emptyForm()
            }
        },
        payload() {
            if (this.isEdit) {
                return this.changes
            }
            const fields = { name: this.form.name.trim(), local: this.form.local }
            ;["uuid", "type", "sector", "nationality", "description", "contacts"].forEach((field) => {
                const value = this.form[field].trim()
                if (value !== "") {
                    fields[field] = value
                }
            })
            const domains = domainLines(this.form.restricted_to_domain)
            if (domains.length > 0) {
                fields.restricted_to_domain = domains
            }
            return fields
        },
        save() {
            if (!this.canSave || this.saving) {
                return
            }
            this.saving = true
            this.error = null
            const name = this.form.name.trim()
            const request = this.isEdit
                ? api.edit(this.server.id, this.org.id, this.payload())
                : api.add(this.server.id, this.payload())
            request
                .then((data) => {
                    const saved = (data && data.Organisation) || { uuid: (this.form.uuid.trim() || "").toLowerCase() || null }
                    this.$bvToast.toast(this.isEdit ? `${name} was saved on ${this.server.name}` : `${name} was added to ${this.server.name}`, {
                        title: this.isEdit ? "Organisation saved" : "Organisation added",
                        variant: "success",
                        solid: true,
                    })
                    this.$emit("saved", saved)
                    this.$bvModal.hide("modal-organisation-form")
                })
                .catch((error) => {
                    this.error = error.message
                    this.errorField = error.field || null
                })
                .finally(() => { this.saving = false })
        },
    },
}
</script>

